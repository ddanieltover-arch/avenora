/**
 * Embeds public/avenora-header-logo.jpg as a TS module for CID email attachments.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const logoPath = path.join(root, 'public', 'avenora-header-logo.jpg');
const outPath = path.join(root, 'src', 'server', 'emails', 'assets', 'emailLogo.ts');

const base64 = fs.readFileSync(logoPath).toString('base64');
const source = `/**
 * @license Apache-2.0
 * Inline email header logo (JPEG base64) so clients do not fetch the site.
 * Regenerated by: node scripts/embed-email-logo.mjs
 */

export const EMAIL_LOGO_CONTENT_ID = 'avenora-header-logo';
export const EMAIL_LOGO_FILENAME = 'avenora-header-logo.jpg';
export const EMAIL_LOGO_CONTENT_TYPE = 'image/jpeg';
export const EMAIL_LOGO_BASE64 = ${JSON.stringify(base64)};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, source);
console.log(`[embed-email-logo] Wrote ${outPath} (${base64.length} base64 chars)`);
